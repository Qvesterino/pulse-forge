/** The credits.md body generated from this table (the gate test pins its
 * content against a fresh render so the file can never go stale). */
export function renderCredits(): string {
  const lines: string[] = [
    "# Sample credits",
    "",
    "Licenses of the sample material shipped with KYX. Regenerated by",
    "`tests/sample-license-gate.test.ts` — edit PACK_CREDITS in",
    "`src/sample-library/licenses.ts`, not this file.",
    "",
  ];
  for (const pack of PACK_CREDITS) {
    const info = LICENSES[pack.license];
    lines.push(`## ${pack.pack} — ${info.name}`);
    lines.push("");
    lines.push(`Source: ${pack.sourceUrl}`);
    for (const credit of pack.credits) lines.push(`- ${credit}`);
    lines.push(`- ${info.attribution}`);
    lines.push("");
  }
  return lines.join("\n");
}
