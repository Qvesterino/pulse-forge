/**
 * SAMPLE LICENSE REGISTRY — the redistribution-rights table for everything
 * the app ships or loads as a factory asset.
 *
 * WHY A REGISTRY: the app REDISTRIBUTES raw sample WAVs inside its own
 * binary (unlike a music tool, where "free for your songs" is enough).
 * That is stricter: the license must allow redistribution in a commercial
 * product, and CC-BY adds a credits obligation we fulfil in
 * `public/licenses/credits.md` (generated from this table by
 * `tests/sample-license-gate.test.ts`).
 *
 * NOT allowed by this registry (documented rejections):
 *   - CC-BY-NC — non-commercial excludes a paid/shipped product
 *   - CC-BY-ND — "no derivatives" forbids the sampling itself
 *   - CC-BY-SA — share-alike conflicts with the proprietary app license
 *   - "free for your music" site licenses (LABS, PianoBook, Spitfire…) —
 *     they grant end-user music use, NOT raw-sample redistribution in a
 *     tool. They require a per-pack vendor review before entering here.
 */

export type SampleLicense = "cc0" | "cc-by-3.0" | "cc-by-4.0" | "kyx-original";

export interface LicenseInfo {
  /** SPDX-style short id shown in the credits file. */
  id: SampleLicense;
  name: string;
  /** Full attribution line written into credits.md. */
  attribution: string;
  /** Whether redistribution inside the shipped app is licensed. */
  redistributable: boolean;
}

