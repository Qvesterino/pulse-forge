/** Packs approved for redistribution. Each entry names every obligation the
 * gate test enforces (license + credits line). Grows one entry per pack. */
export interface PackCredits {
  pack: string;
  license: SampleLicense;
  /** Attribution line(s) — written into credits.md verbatim. */
  credits: string[];
  sourceUrl: string;
}

