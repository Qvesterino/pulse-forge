/**
 * Bundle the SKRUTKA phase-dispersion worklet entry into a single
 * classic-script file served from public/skrutka-worklet.js (dev) and copied
 * into dist/ on build. Runs automatically via the predev/prebuild npm hooks.
 *
 * SKRUTKA is a FIRST-PARTY lazy worklet effect (not a vendored suite), so it
 * does NOT belong in the core boot bundle (public/core-worklet.js). The
 * loader loads it on demand only for projects that use the effect (see
 * LAZY_WORKLET_TYPES in src/audio-worklets/loader.ts).
 */
import { build } from "esbuild";

await build({
  entryPoints: ["src/audio-worklets/skrutka-worklet.entry.js"],
  bundle: true,
  format: "iife",
  target: "es2022",
  outfile: "public/skrutka-worklet.js",
  minify: true,
  logLevel: "warning",
  banner: {
    js: "/* SKRUTKA phase dispersion worklet - generated by scripts/build-skrutka-worklet.mjs from src/audio-worklets/skrutka-processor.js. Do not edit. */",
  },
});
console.log("[skrutka] worklet bundle written to public/skrutka-worklet.js");
