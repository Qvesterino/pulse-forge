/**
 * Bundle the STRUNA worklet entry into a single classic-script file served
 * from public/struna-worklet.js (dev) and copied into dist/ on build. Runs
 * automatically via the predev/prebuild npm hooks.
 *
 * STRUNA is a lazy INSTRUMENT worklet: it does NOT belong in the core boot
 * bundle, so the loader loads it on demand only for projects that actually
 * contain a STRUNA track (see INSTRUMENT_WORKLET_TYPES in
 * src/audio-worklets/loader.ts). ADR 0054.
 */
import { build } from "esbuild";

await build({
  entryPoints: ["src/struna-worklet.entry.js"],
  bundle: true,
  format: "iife",
  target: "es2022",
  outfile: "public/struna-worklet.js",
  minify: false,
  logLevel: "warning",
  banner: {
    js: "/* STRUNA worklet - generated by scripts/build-struna-worklet.mjs from src/struna-worklet.entry.js + src/struna/dsp. Do not edit. */",
  },
});
console.log("[struna] worklet bundle written to public/struna-worklet.js");
