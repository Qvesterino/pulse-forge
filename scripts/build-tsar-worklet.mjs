/**
 * Bundle the TSAR worklet entry into a single classic-script file served
 * from public/tsar-worklet.js (dev) and copied into dist/ on build. Runs
 * automatically via the predev/prebuild npm hooks.
 *
 * TSAR is a FLAGSHIP INSTRUMENT worklet: it does NOT belong in the core boot
 * bundle (public/core-worklet.js), so the loader loads it on demand only for
 * projects that actually contain a TSAR track (see TSAR_WORKLET_TYPES in
 * src/audio-worklets/loader.ts).
 */
import { build } from "esbuild";

await build({
  entryPoints: ["src/tsar-worklet.entry.js"],
  bundle: true,
  format: "iife",
  target: "es2022",
  outfile: "public/tsar-worklet.js",
  minify: false,
  logLevel: "warning",
  banner: {
    js: "/* TSAR worklet - generated by scripts/build-tsar-worklet.mjs from src/tsar-worklet.entry.js + src/tsar/dsp. Do not edit. */",
  },
});
console.log("[tsar] worklet bundle written to public/tsar-worklet.js");
