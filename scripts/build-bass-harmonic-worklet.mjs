/**
 * Bundle the KOREŇ bass harmonic worklet entry into a single classic-script
 * file served from public/bass-harmonic-worklet.js (dev) and copied into
 * dist/ on build. Runs automatically via the predev/prebuild npm hooks.
 *
 * KOREŇ is a FIRST-PARTY lazy worklet effect (not a vendored suite), so it
 * does NOT belong in the core boot bundle (public/core-worklet.js). The
 * loader loads it on demand only for projects that use the effect (see
 * LAZY_WORKLET_TYPES in src/audio-worklets/loader.ts).
 */
import { build } from "esbuild";

await build({
  entryPoints: ["src/audio-worklets/bass-harmonic-worklet.entry.js"],
  bundle: true,
  format: "iife",
  target: "es2022",
  outfile: "public/bass-harmonic-worklet.js",
  minify: true,
  logLevel: "warning",
  banner: {
    js: "/* KOREŇ bass harmonic worklet - generated by scripts/build-bass-harmonic-worklet.mjs from src/audio-worklets/bass-harmonic-processor.js. Do not edit. */",
  },
});
console.log("[bass-harmonic] worklet bundle written to public/bass-harmonic-worklet.js");
