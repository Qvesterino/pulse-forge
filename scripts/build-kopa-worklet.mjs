/**
 * Bundle the KOPA worklet entry into a single classic-script file served
 * from public/kopa-worklet.js (dev) and copied into dist/ on build. Runs
 * automatically via the predev/prebuild npm hooks.
 *
 * KOPA is a lazy INSTRUMENT worklet: it does NOT belong in the core boot
 * bundle (public/core-worklet.js), so the loader loads it on demand only for
 * projects that actually contain a KOPA track (see INSTRUMENT_WORKLET_TYPES
 * in src/audio-worklets/loader.ts).
 */
import { build } from "esbuild";

await build({
  entryPoints: ["src/kopa-worklet.entry.js"],
  bundle: true,
  format: "iife",
  target: "es2022",
  outfile: "public/kopa-worklet.js",
  minify: false,
  logLevel: "warning",
  banner: {
    js: "/* KOPA worklet - generated by scripts/build-kopa-worklet.mjs from src/kopa-worklet.entry.js + src/kopa/dsp. Do not edit. */",
  },
});
console.log("[kopa] worklet bundle written to public/kopa-worklet.js");
