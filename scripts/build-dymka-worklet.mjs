/**
 * Bundle the DYMKA worklet entry into a single classic-script file served
 * from public/dymka-worklet.js (dev) and copied into dist/ on build. Runs
 * automatically via the predev/prebuild npm hooks.
 *
 * DYMKA is a lazy INSTRUMENT worklet: it does NOT belong in the core boot
 * bundle, so the loader loads it on demand only for projects that actually
 * contain a DYMKA track (see INSTRUMENT_WORKLET_TYPES in
 * src/audio-worklets/loader.ts). ADR 0054.
 */
import { build } from "esbuild";

await build({
  entryPoints: ["src/dymka-worklet.entry.js"],
  bundle: true,
  format: "iife",
  target: "es2022",
  outfile: "public/dymka-worklet.js",
  minify: false,
  logLevel: "warning",
  banner: {
    js: "/* DYMKA worklet - generated by scripts/build-dymka-worklet.mjs from src/dymka-worklet.entry.js + src/dymka/dsp. Do not edit. */",
  },
});
console.log("[dymka] worklet bundle written to public/dymka-worklet.js");
