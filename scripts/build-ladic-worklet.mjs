/**
 * Bundle the LADIČ worklet entry into a single classic-script file served
 * from public/ladic-worklet.js (dev) and copied into dist/ on build. Runs
 * automatically via the predev/prebuild npm hooks.
 *
 * LADIČ is a lazy INSTRUMENT worklet (ADR 0055): it does NOT belong in the
 * core boot bundle, so the loader loads it on demand only for projects
 * that actually contain a LADIČ track.
 */
import { build } from "esbuild";

await build({
  entryPoints: ["src/ladic-worklet.entry.js"],
  bundle: true,
  format: "iife",
  target: "es2022",
  outfile: "public/ladic-worklet.js",
  minify: false,
  logLevel: "warning",
  banner: {
    js: "/* LADIČ worklet - generated by scripts/build-ladic-worklet.mjs from src/ladic-worklet.entry.js + src/ladic/dsp. Do not edit. */",
  },
});
console.log("[ladic] worklet bundle written to public/ladic-worklet.js");
