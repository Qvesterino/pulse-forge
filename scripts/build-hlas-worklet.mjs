/**
 * Bundle the HĽAS worklet entry into a single classic-script file served
 * from public/hlas-worklet.js (dev) and copied into dist/ on build. Runs
 * automatically via the predev/prebuild npm hooks. ADR 0059.
 */
import { build } from "esbuild";

await build({
  entryPoints: ["src/hlas-worklet.entry.js"],
  bundle: true,
  format: "iife",
  target: "es2022",
  outfile: "public/hlas-worklet.js",
  minify: false,
  logLevel: "warning",
  banner: {
    js: "/* HĽAS worklet - generated by scripts/build-hlas-worklet.mjs from src/hlas-worklet.entry.js + src/hlas/dsp. Do not edit. */",
  },
});
console.log("[hlas] worklet bundle written to public/hlas-worklet.js");
