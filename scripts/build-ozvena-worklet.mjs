/**
 * Bundle the Ozvena worklet entry into a single classic-script file served
 * from public/ozvena-worklet.js (dev) and copied into dist/ on build.
 * Runs automatically via the predev/prebuild npm hooks.
 */
import { build } from "esbuild";

await build({
  entryPoints: ["src/effects/ozvena-worklet.entry.js"],
  bundle: true,
  format: "iife",
  target: "es2022",
  outfile: "public/ozvena-worklet.js",
  minify: false,
  logLevel: "warning",
  banner: {
    js: "/* Ozvena worklet — generated by scripts/build-ozvena-worklet.mjs from src/effects/ozvena-worklet.entry.js + vendored ozvena-core. Do not edit. */",
  },
});
console.log("[ozvena] worklet bundle written to public/ozvena-worklet.js");
