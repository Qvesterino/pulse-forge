/**
 * Bundle the REZONANS worklet entry into a single classic-script file served
 * from public/rezonans-worklet.js (dev) and copied into dist/ on build.
 * Runs automatically via the predev/prebuild npm hooks.
 */
import { build } from "esbuild";

await build({
  entryPoints: ["src/effects/rezonans-worklet.entry.js"],
  bundle: true,
  format: "iife",
  target: "es2022",
  outfile: "public/rezonans-worklet.js",
  // Preserve identifiers for useful worklet stack traces while keeping this
  // lazy bundle below its dedicated 64 KB physical-size budget.
  minifyWhitespace: true,
  logLevel: "warning",
  banner: {
    js: "/* REZONANS worklet — generated by scripts/build-rezonans-worklet.mjs from src/effects/rezonans-worklet.entry.js + rezonans-core. Do not edit. */",
  },
});
console.log("[rezonans] worklet bundle written to public/rezonans-worklet.js");
