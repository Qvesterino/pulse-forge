/**
 * Bundle the Ultina worklet entry into a single classic-script file served
 * from public/ultina-worklet.js (dev) and copied into dist/ on build.
 * Runs automatically via the predev/prebuild npm hooks.
 */
import { build } from "esbuild";

await build({
  entryPoints: ["src/effects/ultina-worklet.entry.js"],
  bundle: true,
  format: "iife",
  target: "es2022",
  outfile: "public/ultina-worklet.js",
  minify: false,
  logLevel: "warning",
  banner: {
    js: "/* Ultina worklet — generated by scripts/build-ultina-worklet.mjs from src/effects/ultina-worklet.entry.js + vendored ultina-core. Do not edit. */",
  },
});
console.log("[ultina] worklet bundle written to public/ultina-worklet.js");
