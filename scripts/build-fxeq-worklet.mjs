/**
 * Bundle the FXEQ worklet entry into a single classic-script file served
 * from public/fxeq-worklet.js (dev) and copied into dist/ on build.
 *
 * The vendored fxeq-core is many modules — AudioWorklet.addModule needs one
 * self-contained file, so esbuild prebundles it. Run automatically via the
 * predev/prebuild npm hooks.
 */
import { build } from "esbuild";

await build({
  entryPoints: ["src/effects/fxeq-worklet.entry.js"],
  bundle: true,
  format: "iife",
  target: "es2022",
  outfile: "public/fxeq-worklet.js",
  minify: false,
  logLevel: "warning",
  banner: {
    js: "/* FXEQ worklet — generated by scripts/build-fxeq-worklet.mjs from src/effects/fxeq-worklet.entry.ts + vendored fxeq-core. Do not edit. */",
  },
});
console.log("[fxeq] worklet bundle written to public/fxeq-worklet.js");
