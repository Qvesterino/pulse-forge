/**
 * Bundle the CHORÁL worklet entry into a single classic-script file served
 * from public/choral-worklet.js (dev) and copied into dist/ on build. Runs
 * automatically via the predev/prebuild npm hooks.
 *
 * CHORÁL is a lazy INSTRUMENT worklet: it does NOT belong in the core boot
 * bundle, so the loader loads it on demand only for projects that actually
 * contain a CHORÁL track (see INSTRUMENT_WORKLET_TYPES in
 * src/audio-worklets/loader.ts). ADR 0054.
 */
import { build } from "esbuild";

await build({
  entryPoints: ["src/choral-worklet.entry.js"],
  bundle: true,
  format: "iife",
  target: "es2022",
  outfile: "public/choral-worklet.js",
  minify: false,
  logLevel: "warning",
  banner: {
    js: "/* CHORÁL worklet - generated by scripts/build-choral-worklet.mjs from src/choral-worklet.entry.js + src/choral/dsp. Do not edit. */",
  },
});
console.log("[choral] worklet bundle written to public/choral-worklet.js");
