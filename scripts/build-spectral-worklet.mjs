/**
 * Bundle the PORTAL spectral worklet entry into a single classic-script file
 * served from public/spectral-worklet.js (dev) and copied into dist/ on build.
 * Runs automatically via the predev/prebuild npm hooks.
 *
 * PORTAL is a FIRST-PARTY lazy worklet effect (not a vendored suite), so it does
 * NOT belong in the core boot bundle (public/core-worklet.js). That is not a
 * style choice: core-worklet.js sits at 148.8 KB against a 150 KB gate, and
 * scripts/check-bundle-size.mjs:235-240 records that kaskada's spectral DSP is
 * what forced that budget from 120 -> 150 in the first place (ADR 0038, D1).
 *
 * The loader pulls it in on demand only for projects that actually use the
 * effect — see LAZY_WORKLET_TYPES in src/audio-worklets/loader.ts.
 */
import { build } from "esbuild";

await build({
  entryPoints: ["src/effects/spectral-worklet.entry.js"],
  bundle: true,
  format: "iife",
  target: "es2022",
  outfile: "public/spectral-worklet.js",
  minify: true,
  logLevel: "warning",
  banner: {
    js: "/* PORTAL spectral worklet - generated by scripts/build-spectral-worklet.mjs from src/effects/spectral-worklet.entry.js + spectral-core. Do not edit. */",
  },
});
console.log("[spectral] worklet bundle written to public/spectral-worklet.js");
