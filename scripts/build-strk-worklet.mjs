/**
 * Bundle the ŠTRK worklet entry into a single classic-script file served
 * from public/strk-worklet.js (dev) and copied into dist/ on build. Runs
 * automatically via the predev/prebuild npm hooks.
 *
 * ŠTRK is a lazy INSTRUMENT worklet: it does NOT belong in the core boot
 * bundle (public/core-worklet.js), so the loader loads it on demand only for
 * projects that actually contain a ŠTRK track (see INSTRUMENT_WORKLET_TYPES
 * in src/audio-worklets/loader.ts).
 */
import { build } from "esbuild";

await build({
  entryPoints: ["src/strk-worklet.entry.js"],
  bundle: true,
  format: "iife",
  target: "es2022",
  outfile: "public/strk-worklet.js",
  minify: false,
  logLevel: "warning",
  banner: {
    js: "/* ŠTRK worklet - generated by scripts/build-strk-worklet.mjs from src/strk-worklet.entry.js + src/strk/dsp. Do not edit. */",
  },
});
console.log("[strk] worklet bundle written to public/strk-worklet.js");
