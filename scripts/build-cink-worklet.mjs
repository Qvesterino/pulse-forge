/**
 * Bundle the CINK worklet entry into a single classic-script file served
 * from public/cink-worklet.js (dev) and copied into dist/ on build. Runs
 * automatically via the predev/prebuild npm hooks.
 *
 * CINK is a lazy INSTRUMENT worklet: it does NOT belong in the core boot
 * bundle, so the loader loads it on demand only for projects that actually
 * contain a CINK track (see INSTRUMENT_WORKLET_TYPES in
 * src/audio-worklets/loader.ts). ADR 0054.
 */
import { build } from "esbuild";

await build({
  entryPoints: ["src/cink-worklet.entry.js"],
  bundle: true,
  format: "iife",
  target: "es2022",
  outfile: "public/cink-worklet.js",
  minify: false,
  logLevel: "warning",
  banner: {
    js: "/* CINK worklet - generated by scripts/build-cink-worklet.mjs from src/cink-worklet.entry.js + src/cink/dsp. Do not edit. */",
  },
});
console.log("[cink] worklet bundle written to public/cink-worklet.js");
