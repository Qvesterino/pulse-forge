const NL = String.fromCharCode(10);
function must(cond, what) { if (!cond) { console.error("ANCHOR FAIL: " + what); process.exit(1); } }

// ── H. kyx_routing + kyx_takes executors (before executeBatchTool) ─────────
const batchAnchor = "/** kyx_batch — sequential multi-call with optional ONE-undo-frame folding.";
